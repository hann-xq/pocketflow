import {
  registerDecorator,
  ValidationOptions,
  ValidatorConstraint,
  ValidatorConstraintInterface,
} from 'class-validator';

// NL + 2 check digits + 4-letter bank code + 10-digit account number = 18 chars
// https://wise.com/gb/iban/netherlands
const DUTCH_IBAN_REGEX = /^NL\d{2}[A-Z]{4}\d{10}$/;

@ValidatorConstraint()
export class IsDutchIbanConstraint implements ValidatorConstraintInterface {
  validate(value: unknown) {
    if (typeof value !== 'string') {
      return false;
    }

    if (!DUTCH_IBAN_REGEX.test(value)) {
      return false;
    }

    return isValidIbanChecksum(value);
  }

  defaultMessage() {
    return '$value is not a valid Dutch IBAN';
  }
}

// https://en.wikipedia.org/wiki/International_Bank_Account_Number#Validating_the_IBAN
// Generated by Claude Opus (4.6).
function isValidIbanChecksum(iban: string): boolean {
  // Rearrange: move first 4 chars to the end, then replace letters with numbers (A=10..Z=35)
  const rearranged = iban.slice(4) + iban.slice(0, 4);
  const numeric = rearranged
    .split('')
    .map((char) => {
      const code = char.charCodeAt(0);
      return code >= 65 && code <= 90 ? String(code - 55) : char;
    })
    .join('');

  // Compute the large number mod 97 digit-by-digit to avoid floating point issues
  let remainder = 0;
  for (const char of numeric) {
    remainder = (remainder * 10 + parseInt(char, 10)) % 97;
  }
  return remainder === 1;
}

export function IsDutchIban(validationOptions?: ValidationOptions) {
  return function (object: object, propertyName: string) {
    registerDecorator({
      target: object.constructor,
      propertyName,
      options: validationOptions,
      validator: IsDutchIbanConstraint,
    });
  };
}
